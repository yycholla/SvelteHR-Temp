			{columns}
			loading={$teamReports.fetching}
			searchable={false}
			selectable={true}
			onSelectionChange={(selected) => (selectedReports = selected)}
			onRowClick={handleRowClick}
			pagination={{
				page: currentPage,
				pageSize,
				total: $teamReports.data?.teamReports?.totalCount || 0,
				pageSizes: [10, 20, 50, 100]
